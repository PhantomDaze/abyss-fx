#!/usr/bin/env node
/* 构建 Web 部署产物：把 css/js 合并成两个文件，源码与发布目录分离。
   用法：node tools/build-web.mjs
   输出：dist/web/（index.html + css/app.bundle.css + js/app.bundle.js + _headers + .nojekyll）
*/
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'dist', 'web');
const INDEX = path.join(ROOT, 'index.html');

function read(rel) {
  return fs.readFileSync(path.join(ROOT, rel), 'utf8');
}

function fail(msg) {
  console.error('build-web: ' + msg);
  process.exit(1);
}

if (!fs.existsSync(INDEX)) fail('找不到 index.html');

const html = read('index.html');
const cssRe = /<link\b[^>]*\bhref="(css\/[^"?]+\.css)(?:\?[^"]*)?"[^>]*>/g;
const jsRe = /<script\b[^>]*\bsrc="(js\/[^"?]+\.js)(?:\?[^"]*)?"[^>]*><\/script>/g;
const cssFiles = [...html.matchAll(cssRe)].map((m) => m[1]);
const jsFiles = [...html.matchAll(jsRe)].map((m) => m[1]);

if (!cssFiles.length) fail('index.html 中没有找到 css 引用');
if (!jsFiles.length) fail('index.html 中没有找到 js 引用');
for (const f of [...cssFiles, ...jsFiles]) {
  if (!fs.existsSync(path.join(ROOT, f))) fail('缺少源文件: ' + f);
}

const banner = '/*! ABYSS FX bundled asset. Generated by tools/build-web.mjs. Do not edit. */\n';
const cssBundle = banner + cssFiles.map((f) => `/* ${f} */\n${read(f)}`).join('\n');
const jsBundle = banner + jsFiles.map((f) => `/* ${f} */\n${read(f)}`).join('\n;\n');
const hash = crypto.createHash('sha256').update(cssBundle).update(jsBundle).digest('hex').slice(0, 8);

let outHtml = html;
let cssReplaced = false;
outHtml = outHtml.replace(cssRe, () => {
  if (cssReplaced) return '';
  cssReplaced = true;
  return `<link rel="stylesheet" href="css/app.bundle.css?v=${hash}">`;
});
let jsReplaced = false;
outHtml = outHtml.replace(jsRe, () => {
  if (jsReplaced) return '';
  jsReplaced = true;
  return `<script defer src="js/app.bundle.js?v=${hash}"></script>`;
});
outHtml = outHtml
  .replace('<head>', '<head>\n<!-- 由 tools/build-web.mjs 生成，请勿直接修改；源码见 index.html / css / js -->')
  .replace(/\n{3,}/g, '\n\n');

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(path.join(OUT, 'css'), { recursive: true });
fs.mkdirSync(path.join(OUT, 'js'), { recursive: true });
fs.writeFileSync(path.join(OUT, 'index.html'), outHtml);
fs.writeFileSync(path.join(OUT, 'css', 'app.bundle.css'), cssBundle);
fs.writeFileSync(path.join(OUT, 'js', 'app.bundle.js'), jsBundle);
fs.writeFileSync(path.join(OUT, '.nojekyll'), '');
fs.writeFileSync(path.join(OUT, '_headers'), [
  '/index.html',
  '  Cache-Control: public, max-age=0, must-revalidate',
  '',
  '/css/*',
  '  Cache-Control: public, max-age=31536000, immutable',
  '',
  '/js/*',
  '  Cache-Control: public, max-age=31536000, immutable',
  '',
  '/*',
  '  X-Content-Type-Options: nosniff',
  '  Referrer-Policy: strict-origin-when-cross-origin',
  '',
].join('\n'));

// 运行时会用到的静态资源（当前为空，保留扩展位）
const assetsDir = path.join(ROOT, 'assets');
if (fs.existsSync(assetsDir) && fs.readdirSync(assetsDir).length) {
  fs.cpSync(assetsDir, path.join(OUT, 'assets'), { recursive: true });
}

function kib(n) {
  return (n / 1024).toFixed(1) + ' KiB';
}

const sizes = [
  ['index.html', path.join(OUT, 'index.html')],
  ['css/app.bundle.css', path.join(OUT, 'css', 'app.bundle.css')],
  ['js/app.bundle.js', path.join(OUT, 'js', 'app.bundle.js')],
];
console.log(`built dist/web (v=${hash})`);
for (const [name, file] of sizes) console.log(`  ${name.padEnd(22)} ${kib(fs.statSync(file).size)}`);
console.log(`  ${'首屏请求数'.padEnd(22)} 3（HTML + 1 CSS + 1 JS）`);
